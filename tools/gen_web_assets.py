#!/usr/bin/env python3
# Embed the web/ directory into a C source file (src/dsd_web_assets.c).
# Usage: gen_web_assets.py <web_dir> <output.c>
import os, sys

MIME = {
    '.html': 'text/html; charset=utf-8',
    '.js':   'text/javascript; charset=utf-8',
    '.css':  'text/css; charset=utf-8',
    '.json': 'application/json',
    '.svg':  'image/svg+xml',
    '.png':  'image/png',
    '.ico':  'image/x-icon',
    '.woff2': 'font/woff2',
    '.txt':  'text/plain; charset=utf-8',
    '.webmanifest': 'application/manifest+json',
    '.map':  'application/json',
}

def c_bytes(data):
    out = []
    for i, b in enumerate(data):
        if i % 20 == 0:
            out.append('\n  ')
        out.append('%d,' % b)
    return ''.join(out)

def main():
    web_dir = sys.argv[1]
    out_path = sys.argv[2]
    files = []
    for root, _dirs, names in os.walk(web_dir):
        for n in sorted(names):
            full = os.path.join(root, n)
            rel = '/' + os.path.relpath(full, web_dir).replace(os.sep, '/')
            files.append((rel, full))
    files.sort()

    lines = []
    lines.append('/* Auto-generated by tools/gen_web_assets.py - do not edit. */')
    lines.append('#include "dsd_web.h"')
    lines.append('')
    for idx, (rel, full) in enumerate(files):
        with open(full, 'rb') as f:
            data = f.read()
        lines.append('static const unsigned char asset_%d[] = {%s\n};' % (idx, c_bytes(data)))
    lines.append('')
    lines.append('const web_asset web_assets[] = {')
    for idx, (rel, full) in enumerate(files):
        ext = os.path.splitext(full)[1].lower()
        mime = MIME.get(ext, 'application/octet-stream')
        with open(full, 'rb') as f:
            n = len(f.read())
        lines.append('  { "%s", "%s", asset_%d, %d },' % (rel, mime, idx, n))
    lines.append('};')
    lines.append('const unsigned int web_assets_count = %d;' % len(files))
    lines.append('')

    text = '\n'.join(lines)
    # avoid rewriting (and retriggering make) when nothing changed
    if os.path.exists(out_path):
        with open(out_path, 'r') as f:
            if f.read() == text:
                return
    with open(out_path, 'w') as f:
        f.write(text)

if __name__ == '__main__':
    main()
