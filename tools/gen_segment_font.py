#!/usr/bin/env python3
# Build the 7-segment display face the web UI uses for its readouts (tuned frequency, slot ids):
# digits, '.', ':', '-' and spaces, slanted like a receiver LCD. Every digit has the same advance,
# so "8888.888888" drawn dim behind a value lines up segment for segment (the unlit segments).
# Usage: gen_segment_font.py <out.woff2>   (needs fontTools and brotli)
import math, sys
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

UPM = 1000
ADV = 620            # digit advance
X0, W, H = 70, 440, 800  # digit box
T, GAP = 92, 14      # segment thickness, gap between segment tips
SLANT = math.tan(math.radians(6))

def skew(p):
    x, y = p
    return (round(x + y * SLANT), round(y))

def hseg(y, xl, xr):
    h = T / 2
    return [(xl + GAP, y), (xl + GAP + h, y + h), (xr - GAP - h, y + h), (xr - GAP, y), (xr - GAP - h, y - h), (xl + GAP + h, y - h)]

def vseg(x, yb, yt):
    h = T / 2
    return [(x, yb + GAP), (x - h, yb + GAP + h), (x - h, yt - GAP - h), (x, yt - GAP), (x + h, yt - GAP - h), (x + h, yb + GAP + h)]

def square(x, y, s):
    return [(x, y), (x, y + s), (x + s, y + s), (x + s, y)]

xl, xr = X0 + T / 2, X0 + W - T / 2
ya, yg, yd = H - T / 2, H / 2, T / 2
SEG = {
    'a': hseg(ya, xl, xr), 'g': hseg(yg, xl, xr), 'd': hseg(yd, xl, xr),
    'f': vseg(xl, yg, ya), 'e': vseg(xl, yd, yg), 'b': vseg(xr, yg, ya), 'c': vseg(xr, yd, yg),
}
DIGITS = {'0': 'abcdef', '1': 'bc', '2': 'abged', '3': 'abgcd', '4': 'fgbc', '5': 'afgcd',
          '6': 'afgecd', '7': 'abc', '8': 'abcdefg', '9': 'abcdfg'}

def draw(polys):
    pen = TTGlyphPen(None)
    for poly in polys:
        pts = [skew(p) for p in poly]
        pen.moveTo(pts[0])
        for p in pts[1:]:
            pen.lineTo(p)
        pen.closePath()
    return pen.glyph()

glyphs, metrics, cmap = {}, {}, {}
def add(name, polys, width, chars=()):
    glyphs[name] = draw(polys)
    metrics[name] = (width, min((skew(p)[0] for poly in polys for p in poly), default=0))
    for ch in chars:
        cmap[ord(ch)] = name

add('.notdef', [square(X0, 0, W)], ADV)
add('space', [], ADV, '  ')            # space, figure space: a digit wide
for d, segs in DIGITS.items():
    add('d' + d, [SEG[s] for s in segs], ADV, d)
add('minus', [SEG['g']], ADV, '-−–—')  # hyphen, minus, en and em dash
add('period', [square(40, 0, T)], 40 + T + 40, '.')
add('colon', [square(50, H * 0.22, T), square(50, H * 0.68, T)], 50 + T + 50, ':')

fb = FontBuilder(UPM, isTTF=True)
order = list(glyphs)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=900, descent=-100)
fb.setupNameTable({'familyName': 'DSD Segments', 'styleName': 'Regular',
                   'copyright': 'DSD-FME web UI readout face, generated by tools/gen_segment_font.py'})
fb.setupOS2(sTypoAscender=900, sTypoDescender=-100, sTypoLineGap=0, usWinAscent=900, usWinDescent=100,
            sxHeight=H, sCapHeight=H, fsType=0)
fb.setupPost()
fb.font.flavor = 'woff2'
fb.save(sys.argv[1])
